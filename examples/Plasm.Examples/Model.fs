/// 1. The domain: ordinary immutable F# records, and the rules that decide
///    what may change. Nothing here knows how it is stored except `Db`, which
///    says only what the types cannot.
module Shop.Model

open System
open Plasm

type CustomerId = CustomerId of int64
type OrderId = OrderId of int64
type ProductId = ProductId of int64
type OrderLineId = OrderLineId of int64
type PaymentId = PaymentId of int64
type ArticleId = ArticleId of int64
type TagId = TagId of int64

/// Only valid quantities exist; the database cannot smuggle in a zero.
type Quantity =
    private
    | Quantity of int

    member q.Value =
        let (Quantity v) = q
        v

    static member create(v: int) : Result<Quantity, string> =
        if v > 0 then Ok(Quantity v) else Error $"quantity must be positive, got {v}"

/// Where an order is. A cancelled order always says why: the reason is part of
/// the case, so an order cannot be cancelled without one.
type OrderStatus =
    | Draft
    | Published
    | Cancelled of reason: string

type PaymentStatus =
    | Pending
    | Succeeded
    | Failed

type Customer =
    { Id: CustomerId
      Name: string
      Email: string }

type Product =
    { Id: ProductId
      Sku: string
      Name: string }

/// An order owns its lines: they are read with it and written with it. Its
/// customer and its payments are other aggregates, referred to by id.
type Order =
    { Id: OrderId
      CustomerId: CustomerId option
      Status: OrderStatus
      Total: decimal
      PlacedAt: DateTime
      Version: int
      Lines: OrderLine list }

    /// Usable in queries: Plasm reads the definition and writes it as SQL.
    [<ReflectedDefinition>]
    member o.IsOpen =
        match o.Status with
        | Cancelled _ -> false
        | Draft
        | Published -> true

and OrderLine =
    { Id: OrderLineId
      OrderId: OrderId
      ProductId: ProductId
      Quantity: Quantity
      UnitPrice: decimal }

type Payment =
    { Id: PaymentId
      OrderId: OrderId
      Amount: decimal
      Status: PaymentStatus
      CreatedAt: DateTime }

/// An article links to shared tags: writing the article writes only the links.
type Article =
    { Id: ArticleId
      Title: string
      Tags: Tag list }

and Tag = { Id: TagId; Name: string }

/// Why the shop refuses a change.
type OrderError =
    | NoLines
    | NotDraft
    | AlreadyCancelled
    | ReasonRequired

[<RequireQualifiedAccess>]
module Order =

    let create (customer: CustomerId) (lines: OrderLine list) (now: DateTime) : Result<Order, OrderError> =
        if lines.IsEmpty then
            Error NoLines
        else
            Ok
                { Id = OrderId 0L // generated by the database
                  CustomerId = Some customer
                  Status = Draft
                  Total = lines |> List.sumBy (fun l -> decimal l.Quantity.Value * l.UnitPrice)
                  PlacedAt = now
                  Version = 1
                  Lines = lines }

    let line (product: ProductId) (quantity: Quantity) (price: decimal) : OrderLine =
        { Id = OrderLineId 0L
          OrderId = OrderId 0L // the owner's key, set when the order is written
          ProductId = product
          Quantity = quantity
          UnitPrice = price }

    let publish (order: Order) : Result<Order, OrderError> =
        match order.Status with
        | Draft -> Ok { order with Status = Published }
        | Published
        | Cancelled _ -> Error NotDraft

    let cancel (reason: string) (order: Order) : Result<Order, OrderError> =
        match order.Status with
        | Cancelled _ -> Error AlreadyCancelled
        | _ when String.IsNullOrWhiteSpace reason -> Error ReasonRequired
        | Draft
        | Published -> Ok { order with Status = Cancelled(reason.Trim()) }

    /// The order without the lines `drop` picks, its total recomputed.
    let removeLines (drop: OrderLine -> bool) (order: Order) : Result<Order, OrderError> =
        match order.Status, order.Lines |> List.filter (drop >> not) with
        | Draft, [] -> Error NoLines
        | Draft, kept ->
            Ok
                { order with
                    Lines = kept
                    Total = kept |> List.sumBy (fun l -> decimal l.Quantity.Value * l.UnitPrice) }
        | _ -> Error NotDraft

/// How the domain is stored. The rest follows from the types: a column is
/// named after its field in snake_case; an id is stored as its int64; Quantity
/// is read through its own `create`; PaymentStatus is stored as the case name;
/// OrderStatus, a union with a field, is spread over `status` and
/// `status_reason`; and `OrderLine.ProductId`, a ProductId, references products.
module Db =
    let customers =
        schema<Customer> "customers" {
            identityKey (fun c -> c.Id)
            unique (fun c -> c.Email)
        }

    let products =
        schema<Product> "products" {
            identityKey (fun p -> p.Id)
            unique (fun p -> p.Sku)
        }

    let orders =
        schema<Order> "orders" {
            identityKey (fun o -> o.Id)
            version (fun o -> o.Version)
            ownsOrderedBy (fun o -> o.Lines) (fun l -> l.OrderId) (fun l -> l.Id)
        }

    let orderLines = schema<OrderLine> "order_lines" { identityKey (fun l -> l.Id) }

    let payments = schema<Payment> "payments" { identityKey (fun p -> p.Id) }

    let articles =
        schema<Article> "articles" {
            identityKey (fun a -> a.Id)
            linksOrderedBy (fun a -> a.Tags) "article_tags" "article_id" "tag_id" (fun t -> t.Name)
        }

    let tags =
        schema<Tag> "tags" {
            identityKey (fun t -> t.Id)
            unique (fun t -> t.Name)
        }

    let all: ISchema list = [ customers; products; orders; orderLines; payments; articles; tags ]

    /// Checked once at start-up; every problem is reported with model and field.
    let model = Model.buildOrFail [] all
