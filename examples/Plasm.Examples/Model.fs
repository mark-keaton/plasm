/// 1. The domain: ordinary immutable F# records, and the rules that decide
///    what may change. Each stored record names its table; everything else
///    about how it is stored follows from its types.
module Shop.Model

open System
open Plasm

type CustomerId = CustomerId of int64
type OrderId = OrderId of int64
type ProductId = ProductId of int64
type OrderLineId = OrderLineId of int64
type PaymentId = PaymentId of int64
type ArticleId = ArticleId of int64
type TagId = TagId of int64

/// Only valid quantities exist; the database cannot smuggle in a zero.
type Quantity =
    private
    | Quantity of int

    member q.Value =
        let (Quantity v) = q
        v

    static member create(v: int) : Result<Quantity, string> =
        if v > 0 then Ok(Quantity v) else Error $"quantity must be positive, got {v}"

/// Where an order is. A cancelled order always says why: the reason is part of
/// the case, so an order cannot be cancelled without one.
type OrderStatus =
    | Draft
    | Published
    | Cancelled of reason: string

type PaymentStatus =
    | Pending
    | Succeeded
    | Failed

[<Table "customers">]
type Customer =
    { Id: CustomerId
      Name: string
      [<Unique>]
      Email: string }

[<Table "products">]
type Product =
    { Id: ProductId
      [<Unique>]
      Sku: string
      Name: string }

/// An order owns its lines, which hold its key: they are read with it, in the
/// order of their key, and written with it. Its customer and its payments are
/// other aggregates, referred to by id.
[<Table "orders">]
type Order =
    { Id: OrderId
      CustomerId: CustomerId option
      Status: OrderStatus
      Total: decimal
      PlacedAt: DateTime
      [<Version>]
      Version: int
      Lines: OrderLine list }

    /// Usable in queries: Plasm reads the definition and writes it as SQL.
    [<ReflectedDefinition>]
    member o.IsOpen =
        match o.Status with
        | Cancelled _ -> false
        | Draft
        | Published -> true

and [<Table "order_lines">] OrderLine =
    { Id: OrderLineId
      OrderId: OrderId
      ProductId: ProductId
      Quantity: Quantity
      UnitPrice: decimal }

[<Table "payments">]
type Payment =
    { Id: PaymentId
      OrderId: OrderId
      Amount: decimal
      Status: PaymentStatus
      CreatedAt: DateTime }

/// A tag, shared by the articles that link to it.
[<Table "tags">]
type Tag =
    { Id: TagId
      [<Unique>]
      Name: string }

/// An article links to shared tags, which hold no article's key: writing the
/// article writes only the links.
[<Table "articles">]
type Article =
    { Id: ArticleId
      Title: string
      [<JoinTable "article_tags"; OrderedBy(nameof the<Tag>.Name)>]
      Tags: Tag list }

/// Why the shop refuses a change.
type OrderError =
    | NoLines
    | NotDraft
    | AlreadyCancelled
    | ReasonRequired

[<RequireQualifiedAccess>]
module Order =

    let create (customer: CustomerId) (lines: OrderLine list) (now: DateTime) : Result<Order, OrderError> =
        if lines.IsEmpty then
            Error NoLines
        else
            Ok
                { Id = OrderId 0L // generated by the database
                  CustomerId = Some customer
                  Status = Draft
                  Total = lines |> List.sumBy (fun l -> decimal l.Quantity.Value * l.UnitPrice)
                  PlacedAt = now
                  Version = 1
                  Lines = lines }

    let line (product: ProductId) (quantity: Quantity) (price: decimal) : OrderLine =
        { Id = OrderLineId 0L
          OrderId = OrderId 0L // the owner's key, set when the order is written
          ProductId = product
          Quantity = quantity
          UnitPrice = price }

    let publish (order: Order) : Result<Order, OrderError> =
        match order.Status with
        | Draft -> Ok { order with Status = Published }
        | Published
        | Cancelled _ -> Error NotDraft

    let cancel (reason: string) (order: Order) : Result<Order, OrderError> =
        match order.Status with
        | Cancelled _ -> Error AlreadyCancelled
        | _ when String.IsNullOrWhiteSpace reason -> Error ReasonRequired
        | Draft
        | Published -> Ok { order with Status = Cancelled(reason.Trim()) }

    /// The order without the lines `drop` picks, its total recomputed.
    let removeLines (drop: OrderLine -> bool) (order: Order) : Result<Order, OrderError> =
        match order.Status, order.Lines |> List.filter (drop >> not) with
        | Draft, [] -> Error NoLines
        | Draft, kept ->
            Ok
                { order with
                    Lines = kept
                    Total = kept |> List.sumBy (fun l -> decimal l.Quantity.Value * l.UnitPrice) }
        | _ -> Error NotDraft

/// The model: the records that are not owned. The rest follows from the
/// types: a column is named after its field in snake_case; an id is stored as
/// its int64 and generated by the database; Quantity is read through its own
/// `create`; PaymentStatus is stored as the case name; OrderStatus, a union
/// with a field, is spread over `status` and `status_reason`; and
/// `OrderLine.ProductId`, a ProductId, references products.
module Db =
    let all = [ typeof<Customer>; typeof<Product>; typeof<Order>; typeof<Payment>; typeof<Article>; typeof<Tag> ]

    /// Checked once at start-up; every problem is reported with model and field.
    let model = Model.buildOrFail [] all
