/// 3. Changes are explicit values; validation is pure.
module Shop.Writes

open System
open System.Collections.Generic
open Plasm
open Shop.Model

let newOrder customer =
    { Id = OrderId 0L // generated by the database
      CustomerId = Some customer
      Status = Draft
      Total = 0m
      CancellationReason = None
      PlacedAt = DateTime.UtcNow
      Version = 1
      Customer = NotLoaded
      Lines = NotLoaded
      Payments = NotLoaded }

let newLine (product: ProductId) quantity price =
    match Quantity.create quantity with
    | Ok q ->
        Ok
            { Id = OrderLineId 0L
              OrderId = OrderId 0L // set from the parent on insert
              ProductId = product
              Quantity = q
              UnitPrice = price
              Product = NotLoaded }
    | Error e -> Error e

let validateOrder (cs: Changeset<Order>) =
    cs
    |> Changeset.validateRange((fun o -> o.Total), min = 0m)
    |> Changeset.validateOptionalLength((fun o -> o.CancellationReason), max = 200)

/// An order with its lines, inserted atomically.
let placeOrder customer (lines: OrderLine list) =
    let total = lines |> List.sumBy (fun l -> decimal l.Quantity.Value * l.UnitPrice)

    Changeset.insert { newOrder customer with Total = total }
    |> validateOrder
    |> Changeset.putChildren((fun o -> o.Lines), lines |> List.map Changeset.insert)

/// External input may only touch the fields named here.
let cancelFromForm (form: IReadOnlyDictionary<string, string>) (order: Order) =
    Changeset.update order
    |> Changeset.set((fun o -> o.Status), Cancelled)
    |> Changeset.cast(form, fun o -> o.CancellationReason)
    |> Changeset.validateRequired(fun o -> o.CancellationReason)
    |> validateOrder

/// Keep only these lines; Lines declares OnReplace.Delete, so the others go.
let keepOnly (order: Order) (kept: OrderLine list) =
    Changeset.update order
    |> Changeset.replaceChildren((fun o -> o.Lines), ReplaceScope.allChildren, kept |> List.map Changeset.update)

/// An update from partial data (e.g. a projection): only the stated fields are written.
let publishByKey (id: OrderId) (version: int) =
    Changeset.forKey((fun (o: Order) -> o.Id), id)
    |> Changeset.expectVersion version
    |> Changeset.set((fun o -> o.Status), Published)

let registerCustomer name email =
    Changeset.insert { Id = CustomerId 0L; Name = name; Email = email; Orders = NotLoaded }
    |> Changeset.validateFormat((fun c -> c.Email), "^[^@\\s]+@[^@\\s]+$")
    |> Changeset.uniqueConstraint((fun c -> c.Email), "customers_email_key")

/// 4. Transactions are values too; `let!` passes results between named steps.
let checkout name email (product: ProductId) =
    transaction {
        let! customer = Tx.insert "customer" (registerCustomer name email)

        let line =
            match newLine product 2 9.99m with
            | Ok l -> l
            | Error e -> failwith e

        let! order = Tx.insert "order" (placeOrder customer.Id [ line ])
        return customer, order
    }

// -- Bulk writes ----------------------------------------------------------------

/// One UPDATE for every stale draft; versions are incremented.
let expireDrafts (before: DateTime) =
    Bulk.update (
        plasm { for o in Db.orders do where (o.Status = Draft && o.PlacedAt < before) },
        fun o -> { o with Status = Cancelled; CancellationReason = Some "expired" }
    )

/// Insert new products and rename existing ones, matched on the SKU.
let syncCatalogue (products: Product list) =
    Bulk.upsert (products, (fun p -> p.Sku), fun current incoming -> { current with Name = incoming.Name })

// -- Many-to-many links ---------------------------------------------------------------

/// Make `tags` the article's complete set of tags. Only join-table rows change.
let retag (article: Article) (tags: Tag list) =
    Changeset.update article |> Changeset.putLinks ((fun a -> a.Tags), tags)
