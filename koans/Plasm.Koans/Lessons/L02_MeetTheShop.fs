/// Lesson 02: Meet the shop.
module Plasm.Koans.Lessons.L02_MeetTheShop

open Plasm
open Plasm.Koans
open Plasm.Koans.Shop

let lesson =
    Lesson.make
        "Meet the shop"
        [ Koan.Task(
              "Every koan is given k",
              fun k ->
                  task {
                      // Every koan is a function, fun k -> ... (the line above the
                      // code): k is what the koan is given (KoanContext, under Given).
                      // k.Repo is a repository, Plasm's way in to the koans database.
                      // Count asks how many rows a query matches; Query.from
                      // Db.customers is every row of the customers table.
                      let! customers = k.Repo.Count(Query.from Db.customers)
                      customers |> shouldBe (Ok __)
                  }
          )

          Koan.Task(
              "ok opens a Result",
              fun k ->
                  task {
                      // A repo answers with a Result: Ok with the answer, or Error
                      // saying what went wrong. ok (under Given) takes the value out
                      // of an Ok; given an Error it fails the koan and shows the error.
                      let! orders = k.Repo.Count(Query.from Db.orders)
                      orders |> shouldBe (Ok 4L)
                      ok orders |> shouldBe __
                  }
          )

          Koan.Task(
              "k.Commands shows what was sent",
              fun k ->
                  task {
                      // k.Commands lists the SQL this koan has sent to the database,
                      // in order. A koan has sent nothing when it starts.
                      k.Commands.Length |> shouldBe __
                      let! _ = k.Repo.Count(Query.from Db.products)
                      k.Commands.Length |> shouldBe __
                  }
          )

          Koan.Task(
              "The shop has three customers",
              fun k ->
                  task {
                      // All reads every row a query matches, each as a record: here
                      // every customer as a Customer (under Given).
                      let! customers = k.Repo.All(Query.from Db.customers)
                      let names = ok customers |> List.map (fun c -> c.Name) |> List.sort
                      names |> shouldBe __
                  }
          )

          Koan.Task(
              "Counting rows",
              fun k ->
                  task {
                      // Count asks the database how many rows there are, without
                      // reading them. The starting data has three products.
                      let! products = k.Repo.Count(Query.from Db.products)
                      ok products |> shouldBe __
                  }
          )

          Koan.Task(
              "The database numbers the rows",
              fun k ->
                  task {
                      // Every table's id is generated by the database: 1, 2, 3 ...
                      // in the order the starting data inserts the rows. The id
                      // comes back wrapped in its own type (CustomerId, in Shop.fs).
                      let! customers = k.Repo.All(Query.from Db.customers)
                      let bob = ok customers |> List.find (fun c -> c.Name = "Bob")
                      bob.Id |> shouldBe __
                  }
          )

          Koan.Task(
              "An order belongs to a customer",
              fun k ->
                  task {
                      // An order's CustomerId says who placed it: the
                      // customer_id column of the orders table.
                      let! customers = k.Repo.All(Query.from Db.customers)
                      let! orders = k.Repo.All(Query.from Db.orders)
                      let ada = ok customers |> List.find (fun c -> c.Name = "Ada")
                      let adas = ok orders |> List.filter (fun o -> o.CustomerId = Some ada.Id)
                      adas.Length |> shouldBe __
                  }
          )

          Koan.Task(
              "An order may have no customer",
              fun k ->
                  task {
                      // customer_id may be null, so CustomerId is an option.
                      let! orders = k.Repo.All(Query.from Db.orders)
                      let fourth = ok orders |> List.find (fun o -> o.Id = OrderId 4L)
                      fourth.CustomerId |> shouldBe __
                  }
          )

          Koan.Task(
              "A koan's changes stay in the koan",
              fun k ->
                  task {
                      // Every koan runs in a sandbox: a transaction that is rolled
                      // back when the koan ends. Inside it, changes are real.
                      // (Changeset.insert describes a new row; lesson 10 explains it.)
                      let! _ = k.Repo.Insert(Changeset.insert (New.customer "Dan" "dan@example.com"))
                      let! customers = k.Repo.Count(Query.from Db.customers)
                      ok customers |> shouldBe __
                  }
          )

          Koan.Task(
              "The next koan starts afresh",
              fun k ->
                  task {
                      // The previous koan inserted Dan. This koan has its own sandbox.
                      let! customers = k.Repo.Count(Query.from Db.customers)
                      ok customers |> shouldBe __
                  }
          ) ]
