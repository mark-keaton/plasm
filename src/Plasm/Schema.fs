/// What an owned or linked list is, internally: a list of the owner's own
/// rows (HasMany), one owned row (HasOne), or links through a join table.
[<RequireQualifiedAccess>]
type internal AssocKind =
    | HasMany
    | HasOne
    | ManyToMany

module internal Paths =

    /// Extracts the property from `fun x -> x.Prop`.
    let tryProperty (e: Expr) =
        match e with
        | Lambda(v, PropertyGet(Some(Var v2), prop, [])) when v = v2 -> Some prop
        | _ -> None

    let property (what: string) (e: Expr) =
        match tryProperty e with
        | Some p -> p
        | None -> Err.config $"{what} must be a direct property access such as (fun x -> x.Field); got {e}"

    let snakeCase (name: string) =
        let sb = Text.StringBuilder()

        name
        |> Seq.iteri (fun i c ->
            if Char.IsUpper c then
                if i > 0 && not (Char.IsUpper name.[i - 1]) then
                    sb.Append('_') |> ignore
                elif i > 0 && i + 1 < name.Length && Char.IsLower name.[i + 1] then
                    sb.Append('_') |> ignore

                sb.Append(Char.ToLowerInvariant c) |> ignore
            else
                sb.Append(c) |> ignore)

        sb.ToString()

/// A many-to-many join table: its name and the columns referencing the owner's
/// and the target's primary keys.
type internal JoinTable =
    { Table: string
      OwnerColumn: string
      TargetColumn: string }

type internal AssocDef =
    { Property: PropertyInfo
      Kind: AssocKind
      /// Null for ManyToMany.
      ForeignKey: PropertyInfo
      Through: JoinTable option
      /// An owned list (`owns`): a plain list, always loaded and written with
      /// its owner (owned-collections.feature).
      Owned: bool
      /// A linked list (`links`): a plain list of shared records, always loaded
      /// with its owner; writing the owner writes only join-table rows.
      Linked: bool
      /// For an owned or linked list: the order its items are read in (default: by key).
      Order: Expr option }

/// Schema definition state (opaque).
type SchemaDef =
    internal
        { Type: Type
          Table: string
          Key: (PropertyInfo * bool) option
          Columns: Map<string, string>
          Version: PropertyInfo option
          Generated: Set<string>
          /// Fields whose values are unique in the table (constraints.feature).
          Unique: Set<string>
          /// Fields of a key type that refer to no row ([<NotReference>]).
          NotReference: Set<string>
          Assocs: AssocDef list }

/// A persistence mapping for the immutable record type `'T`.
/// Build with the `schema<'T> "table" { ... }` computation expression.
type Schema<'T> internal (def: SchemaDef) =
    member internal _.Def = def
    member _.Table = def.Table
    member _.RecordType = typeof<'T>

    interface ISchema with
        member _.Definition = def

/// A schema of any record type, for building a Model.
and ISchema =
    abstract Definition: SchemaDef

/// Builds a `Schema<'T>`. Every operation takes typed property selectors.
type SchemaBuilder<'T> internal (table: string) =

    let add (s: SchemaDef) f : SchemaDef = f s

    member _.Yield(_: unit) : SchemaDef =
        { Type = typeof<'T>
          Table = table
          Key = None
          Columns = Map.empty
          Version = None
          Generated = Set.empty
          Unique = Set.empty
          NotReference = Set.empty
          Assocs = [] }

    member _.Run(def: SchemaDef) : Schema<'T> = Schema<'T>(def)

    /// Primary key whose value is assigned by the application.
    [<CustomOperation("key")>]
    member _.Key(s: SchemaDef, [<ReflectedDefinition>] field: Expr<'T -> 'K>) =
        add s (fun s -> { s with Key = Some(Paths.property "key" field, false) })

    /// Primary key generated by the database (identity / serial). Its value in a
    /// submitted record is ignored on insert and the generated value is returned.
    [<CustomOperation("identityKey")>]
    member _.IdentityKey(s: SchemaDef, [<ReflectedDefinition>] field: Expr<'T -> 'K>) =
        add s (fun s -> { s with Key = Some(Paths.property "identityKey" field, true) })

    /// Overrides the default snake_case column name.
    [<CustomOperation("column")>]
    member _.Column(s: SchemaDef, [<ReflectedDefinition>] field: Expr<'T -> 'F>, name: string) =
        let p = Paths.property "column" field
        add s (fun s -> { s with Columns = s.Columns.Add(p.Name, name) })

    /// Integer optimistic-concurrency version. Updates and deletes require the
    /// stored version to match and increment it.
    [<CustomOperation("version")>]
    member _.Version(s: SchemaDef, [<ReflectedDefinition>] field: Expr<'T -> int>) =
        add s (fun s -> { s with Version = Some(Paths.property "version" field) })

    /// A column whose value is produced by the database on insert (a default).
    /// It is omitted from INSERT and read back from the database.
    [<CustomOperation("generated")>]
    member _.Generated(s: SchemaDef, [<ReflectedDefinition>] field: Expr<'T -> 'F>) =
        let p = Paths.property "generated" field
        add s (fun s -> { s with Generated = s.Generated.Add p.Name })

    /// Records this one owns, as a plain list (`Lines: Line list`): always
    /// loaded with it, in the order of their key, and written with it.
    /// `owner` selects the owned record's field holding this record's key.
    [<CustomOperation("owns")>]
    member _.Owns(s: SchemaDef, [<ReflectedDefinition>] list: Expr<'T -> 'C list>, [<ReflectedDefinition>] owner: Expr<'C -> 'K>) =
        add s (fun s -> SchemaBuilder<'T>.AddOwned(s, list, owner, None))

    /// A record this one owns that may be absent (`Profile: Profile option`):
    /// its own row, holding this record's key in `owner`; always loaded with it
    /// and written with it (owned-records.feature).
    [<CustomOperation("ownsOptional")>]
    member _.OwnsOptional(s: SchemaDef, [<ReflectedDefinition>] one: Expr<'T -> 'C option>, [<ReflectedDefinition>] owner: Expr<'C -> 'K>) =
        add s (fun s -> SchemaBuilder<'T>.AddOwnedOne(s, one, owner))

    /// A record this one owns that must exist (`Settings: Settings`): its own
    /// row, holding this record's key in `owner`; reading an owner without it
    /// is an error naming the field.
    [<CustomOperation("ownsOne")>]
    member _.OwnsOne(s: SchemaDef, [<ReflectedDefinition>] one: Expr<'T -> 'C>, [<ReflectedDefinition>] owner: Expr<'C -> 'K>) =
        add s (fun s -> SchemaBuilder<'T>.AddOwnedOne(s, one, owner))

    static member private AddOwnedOne(s: SchemaDef, one: Expr, owner: Expr) =
        { s with
            Assocs =
                s.Assocs
                @ [ { Property = Paths.property "owns" one
                      Kind = AssocKind.HasOne
                      ForeignKey = Paths.property "owns owner" owner
                      Through = None
                      Owned = true
                      Linked = false
                      Order = None } ] }

    /// Like `owns`, with the order the owned records are read in.
    [<CustomOperation("ownsOrderedBy")>]
    member _.OwnsOrderedBy
        (
            s: SchemaDef,
            [<ReflectedDefinition>] list: Expr<'T -> 'C list>,
            [<ReflectedDefinition>] owner: Expr<'C -> 'K>,
            [<ReflectedDefinition>] order: Expr<'C -> 'O>
        ) =
        add s (fun s -> SchemaBuilder<'T>.AddOwned(s, list, owner, Some(order :> Expr)))

    static member private AddOwned(s: SchemaDef, list: Expr, owner: Expr, order: Expr option) =
        { s with
            Assocs =
                s.Assocs
                @ [ { Property = Paths.property "owns" list
                      Kind = AssocKind.HasMany
                      ForeignKey = Paths.property "owns owner" owner
                      Through = None
                      Owned = true
                      Linked = false
                      Order = order } ] }

    /// Shared records this one links to through `joinTable`, as a plain list
    /// (`Tags: Tag list`): always loaded with it, in the order of their key.
    /// Writing this record writes only join-table rows; the linked records
    /// belong to their own aggregates.
    [<CustomOperation("links")>]
    member _.Links(s: SchemaDef, [<ReflectedDefinition>] list: Expr<'T -> 'C list>, joinTable: string, ownerColumn: string, targetColumn: string) =
        add s (fun s -> SchemaBuilder<'T>.AddLinked(s, list, joinTable, ownerColumn, targetColumn, None))

    /// Like `links`, with the order the linked records are read in.
    [<CustomOperation("linksOrderedBy")>]
    member _.LinksOrderedBy
        (
            s: SchemaDef,
            [<ReflectedDefinition>] list: Expr<'T -> 'C list>,
            joinTable: string,
            ownerColumn: string,
            targetColumn: string,
            [<ReflectedDefinition>] order: Expr<'C -> 'O>
        ) =
        add s (fun s -> SchemaBuilder<'T>.AddLinked(s, list, joinTable, ownerColumn, targetColumn, Some(order :> Expr)))

    static member private AddLinked(s: SchemaDef, list: Expr, joinTable, ownerColumn, targetColumn, order: Expr option) =
        { s with
            Assocs =
                s.Assocs
                @ [ { Property = Paths.property "links" list
                      Kind = AssocKind.ManyToMany
                      ForeignKey = null
                      Through =
                        Some
                            { Table = joinTable
                              OwnerColumn = ownerColumn
                              TargetColumn = targetColumn }
                      Owned = false
                      Linked = true
                      Order = order } ] }

    /// A field whose values are unique in the table. The database holds it
    /// with a unique constraint named <table>_<column>_key (PostgreSQL's
    /// default), which the schema check verifies; a duplicate comes back as
    /// the field's error.
    [<CustomOperation("unique")>]
    member _.Unique(s: SchemaDef, [<ReflectedDefinition>] field: Expr<'T -> 'F>) =
        let p = Paths.property "unique" field
        add s (fun s -> { s with Unique = s.Unique.Add p.Name })

[<AutoOpen>]
module SchemaBuilderExtensions =
    /// Begins a schema definition for the record type `'T` stored in `table`.
    let schema<'T> (table: string) = SchemaBuilder<'T>(table)

