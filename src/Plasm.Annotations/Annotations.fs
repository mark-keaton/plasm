// The attributes a record uses to say how it is stored. Everything else
// follows from its types: the key is the field named Id, a typed id refers to
// the record whose key it is, and a list of stored records is owned when they
// hold the owner's key and linked when they do not.
namespace Plasm

open System

/// The table a record is stored in. Every stored record names its table,
/// owned records included; nothing else in a model is named by hand except a
/// linked list's join table.
[<AttributeUsage(AttributeTargets.Class, AllowMultiple = false)>]
type TableAttribute(name: string) =
    inherit Attribute()
    member _.Name = name

/// The column a field is stored in, when it is not the field's name in snake
/// case: for a table the application did not design, such as one scaffolded
/// from an existing database. A field of a key of several parts is stored in
/// a column per part, named in the order of the key record's fields:
/// `[<Column("repo", "issue_number")>]` (composite-keys.feature).
[<AttributeUsage(AttributeTargets.Property, AllowMultiple = false)>]
type ColumnAttribute([<ParamArray>] names: string[]) =
    inherit Attribute()
    new(name: string) = ColumnAttribute([| name |])
    /// The one column's name (the first, for several).
    member _.Name = if isNull names || names.Length = 0 then null else names.[0]
    /// Every column's name, in order.
    member _.Names = if isNull names then [||] else names

/// The field's values are unique in the table. The database holds it with a
/// unique constraint named <table>_<column>_key, and a duplicate comes back as
/// the field's error. With Within, unique within the fields it names
/// (`Within = [| nameof the<Tag>.Tenant |]`): one uniqueness over them and
/// then this field, <table>_<columns>_key (unique-within.feature).
[<AttributeUsage(AttributeTargets.Property, AllowMultiple = false)>]
type UniqueAttribute() =
    inherit Attribute()
    /// The fields of the same record this field's values are unique within.
    member val Within: string[] = [||] with get, set

/// An integer version: a change or delete requires the stored version to be
/// the one read, and increments it. Without one, a change is checked against
/// every column of the record it was made from.
[<AttributeUsage(AttributeTargets.Property, AllowMultiple = false)>]
type VersionAttribute() =
    inherit Attribute()

/// A column the database fills on insert (a default): left out of the INSERT
/// and read back.
[<AttributeUsage(AttributeTargets.Property, AllowMultiple = false)>]
type GeneratedAttribute() =
    inherit Attribute()

/// On the Id field: the application assigns the key, though it is an integer.
/// An integer key is otherwise generated by the database.
[<AttributeUsage(AttributeTargets.Property, AllowMultiple = false)>]
type AssignedAttribute() =
    inherit Attribute()

/// A field of a key type that does not refer to a row: an id kept after the
/// row it named is gone. No foreign key is expected for it.
[<AttributeUsage(AttributeTargets.Property, AllowMultiple = false)>]
type NotReferenceAttribute() =
    inherit Attribute()

/// A field stored as one jsonb document (json-columns.feature): a record with no
/// table and no Id, a list of them, a list of scalars, or an option of these.
/// Plasm maps it the same way everywhere: records as objects keyed in snake
/// case, None as a missing key, lists as arrays.
[<AttributeUsage(AttributeTargets.Property, AllowMultiple = false)>]
type JsonAttribute() =
    inherit Attribute()

/// On an owned or linked list: the field of its records they are read in
/// order of. Name it with `nameof the<Comment>.At`, so a misspelt or renamed
/// field is a compile error. Without it, the records are read in order of
/// their key.
[<AttributeUsage(AttributeTargets.Property, AllowMultiple = false)>]
type OrderedByAttribute(field: string) =
    inherit Attribute()
    member _.Field = field

/// On a linked list: the join table that holds its links. The columns default
/// to <owner type>_id and <target type>_id in snake case.
[<AttributeUsage(AttributeTargets.Property, AllowMultiple = false)>]
type JoinTableAttribute(name: string, ownerColumn: string, targetColumn: string) =
    inherit Attribute()
    new(name: string) = JoinTableAttribute(name, null, null)
    member _.Name = name
    /// Null when the default applies.
    member _.OwnerColumn = ownerColumn
    /// Null when the default applies.
    member _.TargetColumn = targetColumn

[<AutoOpen>]
module Annotations =
    /// A value of `'T` for naming its fields with nameof, as in
    /// `[<OrderedBy(nameof the<Comment>.At)>]`. Never evaluated.
    let the<'T> : 'T = Unchecked.defaultof<'T>
